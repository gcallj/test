    def get_arrays_for_pack(pack, dates):
        """
        Função auxiliar para calcular OpPrice e Bandas (Erro) para um pack específico
        Retorna arrays numpy: op_price, band_lo_price, band_hi_price
        """
        if pack is None:
            return np.full(len(dates), np.nan), np.full(len(dates), np.nan), np.full(len(dates), np.nan)

        tk  = pack["ticker"]
        tgt = pack["target"]
        best = pack["best"]
        close = pack["close"]
        pred_center = pack["pred_pct_center_full"]

