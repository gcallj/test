        pred = pred_center.reindex(dates).values.astype("float64")

        # Clip operational parts
        L_c = np.clip(L_u, cap_lo, cap_hi)
        H_c = np.clip(H_u, cap_lo, cap_hi)
        pred_c = np.clip(pred, cap_lo, cap_hi)

